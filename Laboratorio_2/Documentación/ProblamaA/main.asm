



.include "m328Pdef.inc"

.def temp      = r16
.def col_idx   = r17
.def offset    = r18
.def max_off   = r19
.def velocidad = r25

.cseg
.org 0x0000
    rjmp RESET
.org 0x0020             
    rjmp TIMER0_OVF_ISR

guardar_codigos:
    ldi r30, low(TablaFlash * 2)
    ldi r31, high(TablaFlash * 2)
    ldi r28, 0x00                 
    ldi r29, 0x01
    
    ldi r23, 205                  
loop_copia:
    lpm r24, Z+
    st Y+, r24
    dec r23
    brne loop_copia
    ret

RESET:
    ldi temp, high(RAMEND)
    out SPH, temp
    ldi temp, low(RAMEND)
    out SPL, temp

    clr r1              

    rcall guardar_codigos

    ldi temp, 0xFF
    out DDRB, temp      
    out DDRD, temp      
    
    ldi temp, 0x00
    out PORTB, temp     
    ldi temp, 0xFF
    out PORTD, temp     

    clr col_idx         
    clr offset          
    
    ldi max_off, 196
    ldi velocidad, 2    ; vel ini (2 es rápido, 5 es normal, 10 es lento)

    ; Prescaler = 8
    ldi temp, (1<<CS01)
    out TCCR0B, temp
    
    ldi temp, (1<<TOIE0)
    sts TIMSK0, temp
    sei                 

MAIN_LOOP:
    mov r20, velocidad  ; 
d1: ldi r21, 255
d2: ldi r22, 100
d3: dec r22
    brne d3
    dec r21
    brne d2
    dec r20
    brne d1

    inc offset
    cp offset, max_off
    brne CONTINUE_SCROLL
    clr offset          

CONTINUE_SCROLL:
    rjmp MAIN_LOOP

TIMER0_OVF_ISR:
    push temp           
    in temp, SREG
    push temp           
    push r30            
    push r31            
    push r23

    ldi temp, 0x00
    out PORTB, temp
    
    ldi r30, 0x00       
    ldi r31, 0x01       
    
    add r30, offset     
    adc r31, r1         
    add r30, col_idx    
    adc r31, r1
    
    ld temp, Z
    com temp            
    out PORTD, temp
    
    ldi temp, 0x01      
    mov r23, col_idx
SHIFT_COL:
    cpi r23, 0
    breq OUT_COL
    lsl temp
    dec r23
    rjmp SHIFT_COL
OUT_COL:
    out PORTB, temp     
    
    inc col_idx
    cpi col_idx, 8
    brne END_ISR
    clr col_idx         

END_ISR:
    pop r23
    pop r31
    pop r30
    pop temp
    out SREG, temp
    pop temp
    reti

TablaFlash:
    ; --- XD ---
    .db 0x63, 0x14, 0x08, 0x14, 0x63, 0x00 ; X
    .db 0x7F, 0x41, 0x41, 0x22, 0x1C, 0x00 ; D
    .db 0x00, 0x00, 0x00, 0x00             ; Espacio
    
    ; --- NO ---
    .db 0x7F, 0x04, 0x08, 0x10, 0x7F, 0x00 ; N
    .db 0x3E, 0x41, 0x41, 0x41, 0x3E, 0x00 ; O
    .db 0x00, 0x00, 0x00, 0x00             ; Espacio
    
    ; --- MAS ---
    .db 0x7F, 0x02, 0x04, 0x02, 0x7F, 0x00 ; M
    .db 0x7C, 0x12, 0x11, 0x12, 0x7C, 0x00 ; A
    .db 0x26, 0x49, 0x49, 0x49, 0x32, 0x00 ; S
    .db 0x00, 0x00, 0x00, 0x00             ; Espacio

    ; --- EVALUACION ---
    .db 0x7F, 0x49, 0x49, 0x49, 0x41, 0x00 ; E
    .db 0x1F, 0x20, 0x40, 0x20, 0x1F, 0x00 ; V
    .db 0x7C, 0x12, 0x11, 0x12, 0x7C, 0x00 ; A
    .db 0x7F, 0x40, 0x40, 0x40, 0x40, 0x00 ; L
    .db 0x3F, 0x40, 0x40, 0x40, 0x3F, 0x00 ; U
    .db 0x7C, 0x12, 0x11, 0x12, 0x7C, 0x00 ; A
    .db 0x3E, 0x41, 0x41, 0x41, 0x22, 0x00 ; C
    .db 0x00, 0x41, 0x7F, 0x41, 0x00, 0x00 ; I
    .db 0x3E, 0x41, 0x41, 0x41, 0x3E, 0x00 ; O
    .db 0x7F, 0x04, 0x08, 0x10, 0x7F, 0x00 ; N
    .db 0x00, 0x00, 0x00, 0x00             ; Espacio

    ; --- CONTINUA ---
    .db 0x3E, 0x41, 0x41, 0x41, 0x22, 0x00 ; C
    .db 0x3E, 0x41, 0x41, 0x41, 0x3E, 0x00 ; O
    .db 0x7F, 0x04, 0x08, 0x10, 0x7F, 0x00 ; N
    .db 0x01, 0x01, 0x7F, 0x01, 0x01, 0x00 ; T
